-- STORAGE PARA IMÁGENES DE SERVICIOS (bucket público existente SIS_AUTO)
-- Ejecutar una sola vez en Supabase > SQL Editor.
-- Agrega la referencia interna del archivo y permite al administrador
-- subir, reemplazar y eliminar imágenes del bucket público SIS_AUTO.

alter table public.servicios
add column if not exists ruta_storage text;

-- Lectura pública de imágenes (el bucket también debe estar marcado como público).
drop policy if exists "SIS_AUTO lectura publica" on storage.objects;
create policy "SIS_AUTO lectura publica"
on storage.objects for select
to anon, authenticated
using (bucket_id = 'SIS_AUTO');

-- Solo usuarios registrados en public.administradores pueden subir imágenes.
drop policy if exists "SIS_AUTO admin inserta" on storage.objects;
create policy "SIS_AUTO admin inserta"
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'SIS_AUTO'
  and exists (
    select 1 from public.administradores a
    where a.usuario_id = auth.uid()
  )
);

-- Se incluye update por compatibilidad futura, aunque esta versión usa nombres únicos.
drop policy if exists "SIS_AUTO admin actualiza" on storage.objects;
create policy "SIS_AUTO admin actualiza"
on storage.objects for update
to authenticated
using (
  bucket_id = 'SIS_AUTO'
  and exists (
    select 1 from public.administradores a
    where a.usuario_id = auth.uid()
  )
)
with check (
  bucket_id = 'SIS_AUTO'
  and exists (
    select 1 from public.administradores a
    where a.usuario_id = auth.uid()
  )
);

-- Solo administradores pueden borrar archivos del bucket.
drop policy if exists "SIS_AUTO admin elimina" on storage.objects;
create policy "SIS_AUTO admin elimina"
on storage.objects for delete
to authenticated
using (
  bucket_id = 'SIS_AUTO'
  and exists (
    select 1 from public.administradores a
    where a.usuario_id = auth.uid()
  )
);
