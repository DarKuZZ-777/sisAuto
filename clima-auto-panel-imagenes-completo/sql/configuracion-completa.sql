-- CLIMA AUTO - estructura y políticas completas
create table if not exists public.administradores (
  usuario_id uuid primary key references auth.users(id) on delete cascade,
  nombre text,
  created_at timestamptz not null default now()
);
create table if not exists public.configuracion_negocio (
  id bigint generated by default as identity primary key,
  nombre_negocio text not null default 'Clima Auto', eslogan text, descripcion text,
  whatsapp text, telefono text, correo text, direccion text, horario text,
  google_maps_url text, facebook_url text, instagram_url text, tiktok_url text, youtube_url text,
  logo_url text, logo_ruta_storage text, portada_url text, portada_ruta_storage text, mensaje_whatsapp text, updated_at timestamptz default now()
);
create table if not exists public.servicios (
  id bigint generated by default as identity primary key,
  nombre text not null, descripcion text, imagen_url text, ruta_storage text, precio_desde numeric(12,2),
  mostrar_precio boolean not null default false, visible boolean not null default true,
  destacado boolean not null default false, orden integer not null default 0,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.trabajos (
  id bigint generated by default as identity primary key,
  titulo text not null, vehiculo text, anio_vehiculo integer, problema text,
  trabajo_realizado text, resultado text, imagen_principal_url text, ruta_storage text, fecha_trabajo date,
  visible boolean not null default true, destacado boolean not null default false,
  orden integer not null default 0, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.trabajo_imagenes (
  id bigint generated by default as identity primary key,
  trabajo_id bigint not null references public.trabajos(id) on delete cascade,
  imagen_url text not null, ruta_storage text, texto_alternativo text,
  orden integer not null default 0
);

